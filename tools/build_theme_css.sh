#!/bin/sh
# Regenerates pk_ui/ui/theme_css.lua from design/theme.css (the Vector Woodland mock).
# Module files must be Lua, so the stylesheet ships as one long string.
set -e
cd "$(dirname "$0")/.."
SRC=design/theme.css
OUT=pk_ui/ui/theme_css.lua
if grep -q ']==]' "$SRC"; then echo "theme.css contains ]==]; pick another long-bracket level" >&2; exit 1; fi
{
  echo "-- GENERATED by tools/build_theme_css.sh from design/theme.css. Do not edit; edit the CSS and regenerate."
  echo ""
  echo "PkCore.ui = PkCore.ui or {}"
  echo "PkCore.ui.theme = PkCore.ui.theme or {}"
  echo ""
  echo "PkCore.ui.theme.mockCss = [==["
  cat "$SRC"
  echo "]==]"
} > "$OUT"
echo "wrote $OUT"
